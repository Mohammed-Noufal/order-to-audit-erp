package com.orderaudit.order_to_audit_erp.sales;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

import jakarta.validation.Valid;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;

/** Request bodies for the sales endpoints. */
public final class SalesRequests {

    private SalesRequests() {
    }

    /** clientUuid is generated by the phone when the order is created, even offline. */
    public record SubmitOrder(
            @NotBlank
            @Pattern(regexp = "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$",
                     message = "must be a UUID")
            String clientUuid,
            @NotNull Long customerId,
            @Size(max = 255) String note,
            @NotEmpty @Valid List<OrderLine> lines) {
    }

    public record OrderLine(
            @NotNull Long itemId,
            @NotNull @Positive @Max(100_000) Integer orderedQty) {
    }

    public record EditOrder(@NotEmpty @Valid List<EditLine> lines) {
    }

    /** Change the approved quantity, the unit price, or both. */
    public record EditLine(
            @NotNull Long lineId,
            @PositiveOrZero @Max(100_000) Integer approvedQty,
            @Positive @Digits(integer = 10, fraction = 2) BigDecimal unitPrice) {
    }

    public record Approve(Boolean allowBackorder) {
    }

    public record Reject(@Size(max = 200) String reason) {
    }

    public record CreateInvoice(LocalDate invoiceDate) {
    }

    public record DispatchInvoice(LocalDate dispatchDate) {
    }
}
